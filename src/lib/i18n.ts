export function translate(lang: string, key: Key, vars?: Record<string, string | number>): string {
  let s = dicts[lang]?.[key] ?? en[key] ?? es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

