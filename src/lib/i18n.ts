// Portugués, francés, ruso y alemán: pendientes de traducir antes de publicar (se ve en inglés).
const dicts: Record<string, Dict> = { es, en, pt, fr, ru, de };

export const LANGS = [
  { code: 'es', native: 'Español' },
  { code: 'en', native: 'English' },
  { code: 'pt', native: 'Português' },
  { code: 'fr', native: 'Français' },
  { code: 'ru', native: 'Русский' },
  { code: 'de', native: 'Deutsch' },
] as const;

export function translate(lang: string, key: Key, vars?: Record<string, string | number>): string {
  let s = dicts[lang]?.[key] ?? en[key] ?? es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function useT() {
  const lang = useStore((s) => s.settings.language);
  return {
    lang,
    t: (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars),
  };
}

/** «hace 5 min», «hoy, 10:32», «ayer, 18:05» o la fecha. */
export function relTime(ts: number, lang: string): string {
  const now = Date.now();
  const d = new Date(ts);
  const time = d.toLocaleTimeString(lang, { hour: '2-digit', minute: '2-digit' });
  const diff = now - ts;
  if (diff < 60_000) return translate(lang, 'when.now');
  if (diff < 3_600_000) return translate(lang, 'when.min', { n: Math.floor(diff / 60_000) });
  const today = new Date();
  const y = new Date(today);
  y.setDate(y.getDate() - 1);
  if (d.toDateString() === today.toDateString()) return translate(lang, 'when.today', { t: time });
  if (d.toDateString() === y.toDateString()) return translate(lang, 'when.yesterday', { t: time });
  return d.toLocaleDateString(lang, { day: 'numeric', month: 'short', year: d.getFullYear() === today.getFullYear() ? undefined : 'numeric' });
}
